/**
 * Renders the operating cycle from `workflow.ai.yml` into `AGENTS.md`.
 *
 * `workflow.ai.yml` is the source of truth for the stages, the skill registry and the quality
 * gates, but no agent toolchain loads it on its own. `AGENTS.md` is the file that Antigravity and
 * the other AGENTS.md-aware tools read automatically, and `CLAUDE.md` imports it for Claude Code.
 * So the cycle has to be *inside* AGENTS.md, and it has to be generated rather than retyped. A
 * hand-copied table drifts within a week, and the copy that drifts is the one agents obey.
 *
 *   node scripts/sync-agent-docs.mjs           write the generated block
 *   node scripts/sync-agent-docs.mjs --check   fail if the block is stale (CI)
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT_DIR = path.resolve(__dirname, '..');
const SOURCE = path.join(ROOT_DIR, 'workflow.ai.yml');
const TARGET = path.join(ROOT_DIR, 'AGENTS.md');

const BEGIN = '<!-- BEGIN GENERATED: ai-workflow-cycle (scripts/sync-agent-docs.mjs) -->';
const END = '<!-- END GENERATED: ai-workflow-cycle -->';
const GENERATED_MARKER = '<!-- generated by scripts/sync-agent-docs.mjs -- do not edit -->';

const lines = fs.readFileSync(SOURCE, 'utf8').replace(/\r\n/g, '\n').split('\n');

const unquote = (value) => value.trim().replace(/^["']|["']$/g, '');
const indentOf = (line) => line.length - line.trimStart().length;

/** Collects the lines of one list entry: the `- key:` line plus everything indented under it. */
function entries(startIndex, endIndex, itemIndent) {
    const found = [];
    let current = null;

    for (let i = startIndex; i < endIndex; i += 1) {
        const line = lines[i];
        if (line.trim() === '' || line.trim().startsWith('#')) continue;

        if (indentOf(line) === itemIndent && line.trimStart().startsWith('- ')) {
            current = [line];
            found.push(current);
        } else if (current && indentOf(line) > itemIndent) {
            current.push(line);
        } else if (indentOf(line) < itemIndent) {
            break;
        }
    }

    return found;
}

const field = (block, key) => {
    const match = block.find((line) => new RegExp(`^\\s*-?\\s*${key}:\\s*.+$`).test(line));
    return match ? unquote(match.replace(new RegExp(`^\\s*-?\\s*${key}:\\s*`), '')) : null;
};

const listField = (block, key) => {
    const inline = field(block, key);
    if (inline && inline.startsWith('[')) {
        return inline.slice(1, -1).split(',').map((entry) => unquote(entry)).filter(Boolean);
    }

    const start = block.findIndex((line) => new RegExp(`^\\s*${key}:\\s*$`).test(line));
    if (start === -1) return inline ? [inline] : [];

    const collected = [];
    for (let i = start + 1; i < block.length; i += 1) {
        const line = block[i];
        if (!line.trimStart().startsWith('- ')) break;
        collected.push(unquote(line.trimStart().slice(2)));
    }
    return collected;
};

const indexOfLine = (pattern) => lines.findIndex((line) => pattern.test(line));

/** A plain `key: "value"` or `key:` + `- item` list living directly under a top-level mapping. */
function topLevelSection(name, nextTopLevel) {
    const start = lines.findIndex((line) => line.trimEnd() === `${name}:`);
    if (start === -1) return [];
    const end = lines.findIndex((line, i) => i > start && nextTopLevel.test(line));
    return lines.slice(start + 1, end === -1 ? lines.length : end);
}

// --- governance ---------------------------------------------------------------------------
const governance = topLevelSection('governance', /^# -{10,}$|^workflows:\s*$/);
const authority = field(governance, 'authority');
const conflictResolution = field(governance, 'conflict_resolution');
const precedence = listField(governance, 'precedence');

// --- stages -------------------------------------------------------------------------------
const stagesStart = indexOfLine(/^\s{4}stages:\s*$/);
const skillsStart = indexOfLine(/^skills:\s*$/);
const stages = entries(stagesStart + 1, skillsStart, 6).map((block) => ({
    phase: field(block, 'phase'),
    name: field(block, 'name'),
    leadSkills: listField(block, 'lead_skills'),
    deliverables: listField(block, 'deliverables').length
        ? listField(block, 'deliverables')
        : (field(block, 'deliverable') ? [field(block, 'deliverable')] : []),
}));

// --- skill registry -----------------------------------------------------------------------
const registryStart = indexOfLine(/^\s{2}registry:\s*$/);
const subagentsStart = indexOfLine(/^subagents:\s*$/);
const skills = entries(registryStart + 1, subagentsStart, 4).map((block) => ({
    name: field(block, 'name'),
    role: field(block, 'role'),
    scope: field(block, 'scope'),
}));

// --- gates --------------------------------------------------------------------------------
const preCommitStart = indexOfLine(/^\s{2}pre_commit:\s*$/);
const rulesStart = indexOfLine(/^\s{2}architectural_rules:\s*$/);
const gates = entries(preCommitStart + 1, rulesStart, 4).map((block) => ({
    name: field(block, 'name'),
    command: field(block, 'command'),
}));

const rules = [];
for (let i = rulesStart + 1; i < lines.length; i += 1) {
    const line = lines[i];
    if (line.trim() === '') continue;
    if (!line.trimStart().startsWith('- ')) break;
    rules.push(unquote(line.trimStart().slice(2)));
}

// --- render -------------------------------------------------------------------------------
const slug = (name) => name.replace(/_/g, '-');
const code = (values) => values.map((value) => `\`${value}\``).join(', ');

const block = [
    BEGIN,
    '',
    '> Generated from `workflow.ai.yml`. Do not edit by hand: run `node scripts/sync-agent-docs.mjs`.',
    '> The YAML is the source of truth, but no toolchain loads it automatically, so the cycle is',
    '> reproduced here, in the file that is loaded automatically.',
    '',
    '### Precedence',
    '',
    authority ? `**${authority}**` : '',
    '',
    ...precedence.map((entry, index) => `${index + 1}. ${entry}`),
    '',
    conflictResolution ? `On conflict: ${conflictResolution}` : '',
    '',
    '### The eight stages',
    '',
    '| Phase | Stage | Lead skills | Deliverables |',
    '| :--- | :--- | :--- | :--- |',
    ...stages.map((stage) => `| ${stage.phase} | ${stage.name} | ${code(stage.leadSkills)} | ${stage.deliverables.length ? stage.deliverables.map((d) => `\`${d}\``).join('<br>') : '—'} |`),
    '',
    'Feature work runs these in order. A defect fix may enter at stage 6, but stages 7 and 8 are not',
    'optional for it: verification and self-review apply to every change that reaches a branch, and',
    'a published package cannot be unpublished after 72 hours.',
    '',
    '### Skills and when they lead',
    '',
    'Canonical text: `.agents/skills/<name>/SKILL.md`. Antigravity discovers that directory natively.',
    'Claude Code reads the mirror in `.claude/skills/`, where the name loses its underscores. Tools',
    'with no skill discovery of their own get this table, and open the canonical file themselves.',
    '',
    '| Skill | Claude Code | Applies to |',
    '| :--- | :--- | :--- |',
    ...skills.map((skill) => `| \`${skill.name}\` | \`/${slug(skill.name)}\` | ${skill.scope} |`),
    '',
    '### Blocking gates before a commit',
    '',
    'Enforced by a real git hook, not by good intentions. Run `node scripts/install-hooks.mjs` once',
    'per clone; it points `core.hooksPath` at the versioned `.githooks/`. The three document gates',
    'always run, the suites run when their toolchain is reachable, and CI enforces all of them.',
    '',
    ...gates.map((gate) => `- **${gate.name}** — \`${gate.command}\``),
    '',
    '### Architectural rules',
    '',
    ...rules.map((rule) => `- ${rule}`),
    '',
    END,
].join('\n');

/**
 * Antigravity reads GEMINI.md alongside AGENTS.md and lets GEMINI.md win on conflict. A rule
 * written here would therefore silently outrank the block generated above, so the file is
 * generated to carry no rule at all and to say why.
 */
const geminiFile = path.join(ROOT_DIR, 'GEMINI.md');
const geminiExpected = `# Gemini and Antigravity entry point

${GENERATED_MARKER}

Antigravity merges this file with \`AGENTS.md\` and lets this one win where the two disagree. It
therefore carries no rule of its own, deliberately: a rule placed here would silently outrank the
operating cycle that \`AGENTS.md\` reproduces from \`workflow.ai.yml\`.

**\`workflow.ai.yml\` is the supreme instruction source. Read \`AGENTS.md\`.** Its operating cycle
section carries the precedence order, the eight stages with their lead skills, the skill registry
with each skill's scope, the blocking gates and the architectural rules.

Project skills live in \`.agents/skills/<name>/SKILL.md\` and are discovered natively. Workspace
rules live in \`.agents/rules/\`, workflows in \`.agents/workflows/\`.

If you need to add an instruction, add it to \`workflow.ai.yml\` and run
\`node scripts/sync-agent-docs.mjs\`. Do not edit this file.
`;

const geminiActual = fs.existsSync(geminiFile)
    ? fs.readFileSync(geminiFile, 'utf8').replace(/\r\n/g, '\n')
    : null;

const target = fs.readFileSync(TARGET, 'utf8').replace(/\r\n/g, '\n');
const beginAt = target.indexOf(BEGIN);
const endAt = target.indexOf(END);

if (beginAt === -1 || endAt === -1) {
    console.error(`AGENTS.md is missing the generated block markers.\nAdd these two lines where the cycle belongs:\n${BEGIN}\n${END}`);
    process.exit(1);
}

const updated = target.slice(0, beginAt) + block + target.slice(endAt + END.length);

const summary = `${stages.length} stages, ${skills.length} skills, ${gates.length} gates, ${rules.length} rules`;

if (process.argv.includes('--check')) {
    const stale = [];
    if (updated !== target) stale.push('AGENTS.md cycle block');
    if (geminiActual !== geminiExpected) stale.push(geminiActual === null ? 'GEMINI.md (missing)' : 'GEMINI.md (stale)');

    if (stale.length > 0) {
        console.error('Out of sync with workflow.ai.yml:');
        for (const entry of stale) console.error(`  - ${entry}`);
        console.error('Run: node scripts/sync-agent-docs.mjs');
        process.exit(1);
    }

    console.log(`AGENTS.md and GEMINI.md are in sync (${summary})`);
} else {
    fs.writeFileSync(TARGET, updated, 'utf8');
    fs.writeFileSync(geminiFile, geminiExpected, 'utf8');
    console.log(`AGENTS.md cycle block and GEMINI.md written (${summary})`);
}
