/**
 * Mirrors the canonical agent skills into `.claude/skills/` so Claude Code discovers them.
 *
 * `.agents/skills/<name>/SKILL.md` stays the single source of truth: it is what
 * `antigravity.yml` registers, what `scripts/validate-skills.mjs` audits, and what every other
 * agent reads. The files written here are pointers, never copies, so the two can never drift
 * into two different sets of instructions.
 *
 *   node scripts/sync-claude-skills.mjs           write the pointers
 *   node scripts/sync-claude-skills.mjs --check   fail if any pointer is missing or stale (CI)
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT_DIR = path.resolve(__dirname, '..');
const SOURCE_DIR = path.join(ROOT_DIR, '.agents', 'skills');
const TARGET_DIR = path.join(ROOT_DIR, '.claude', 'skills');
const ANTIGRAVITY = path.join(ROOT_DIR, 'antigravity.yml');

const GENERATED_MARKER = '<!-- generated by scripts/sync-claude-skills.mjs -- do not edit -->';

/** Claude Code addresses a skill by its directory name, which may not contain underscores. */
const toSlug = (name) => name.replace(/_/g, '-');

function readFrontmatter(file) {
    const raw = fs.readFileSync(file, 'utf8').replace(/\r\n/g, '\n');
    if (!raw.startsWith('---')) return null;

    const end = raw.indexOf('\n---', 3);
    if (end === -1) return null;

    const block = raw.slice(4, end);
    const value = (key) => {
        const match = block.match(new RegExp(`^${key}:\\s*(.+)$`, 'm'));
        return match ? match[1].trim().replace(/^["']|["']$/g, '') : null;
    };

    return { name: value('name'), description: value('description') };
}

/** Scope lines from the antigravity registry, so the pointer says when the skill applies. */
function readScopes() {
    if (!fs.existsSync(ANTIGRAVITY)) return {};

    const lines = fs.readFileSync(ANTIGRAVITY, 'utf8').replace(/\r\n/g, '\n').split('\n');
    const scopes = {};
    let current = null;

    for (const line of lines) {
        const name = line.match(/^\s*-\s*name:\s*(\S+)\s*$/);
        if (name) {
            current = name[1];
            continue;
        }
        const scope = line.match(/^\s*scope:\s*"(.+)"\s*$/);
        if (scope && current) {
            scopes[current] = scope[1];
            current = null;
        }
    }

    return scopes;
}

function pointerFor(name, description, scope) {
    const slug = toSlug(name);
    const canonical = `.agents/skills/${name}/SKILL.md`;
    const summary = scope ? `${description} Scope: ${scope}` : description;

    return `---
name: ${slug}
description: ${summary}
---

# ${slug}

${GENERATED_MARKER}

The instructions for this skill live in \`${canonical}\`, which is also what the Antigravity
pipeline loads under the registry name \`${name}\`. This file only points at them so both
toolchains obey one text.

**Read \`${canonical}\` in full and follow it.** Do not act on this summary.
`;
}

const skills = fs
    .readdirSync(SOURCE_DIR, { withFileTypes: true })
    .filter((entry) => entry.isDirectory())
    .map((entry) => entry.name)
    .sort();

const scopes = readScopes();
const check = process.argv.includes('--check');
const stale = [];
let written = 0;

for (const name of skills) {
    const source = path.join(SOURCE_DIR, name, 'SKILL.md');
    if (!fs.existsSync(source)) {
        console.error(`skipped ${name}: no SKILL.md`);
        continue;
    }

    const frontmatter = readFrontmatter(source);
    if (!frontmatter?.name || !frontmatter?.description) {
        console.error(`skipped ${name}: unreadable frontmatter`);
        continue;
    }

    const expected = pointerFor(frontmatter.name, frontmatter.description, scopes[frontmatter.name]);
    const target = path.join(TARGET_DIR, toSlug(frontmatter.name), 'SKILL.md');
    const actual = fs.existsSync(target) ? fs.readFileSync(target, 'utf8').replace(/\r\n/g, '\n') : null;

    if (actual === expected) continue;

    if (check) {
        stale.push(actual === null ? `${toSlug(frontmatter.name)} (missing)` : `${toSlug(frontmatter.name)} (stale)`);
        continue;
    }

    fs.mkdirSync(path.dirname(target), { recursive: true });
    fs.writeFileSync(target, expected, 'utf8');
    written += 1;
    console.log(`wrote .claude/skills/${toSlug(frontmatter.name)}/SKILL.md`);
}

// A pointer whose source skill was deleted would keep advertising instructions that no longer
// exist, so orphans are an error rather than something to leave lying around.
const expectedSlugs = new Set(skills.map(toSlug));
const orphans = fs.existsSync(TARGET_DIR)
    ? fs
        .readdirSync(TARGET_DIR, { withFileTypes: true })
        .filter((entry) => entry.isDirectory() && !expectedSlugs.has(entry.name))
        .map((entry) => entry.name)
    : [];

for (const orphan of orphans) {
    if (check) {
        stale.push(`${orphan} (orphaned, no matching .agents skill)`);
        continue;
    }
    fs.rmSync(path.join(TARGET_DIR, orphan), { recursive: true, force: true });
    console.log(`removed orphaned .claude/skills/${orphan}`);
}

if (check) {
    if (stale.length > 0) {
        console.error('.claude/skills is out of sync with .agents/skills:');
        for (const entry of stale) console.error(`  - ${entry}`);
        console.error('Run: node scripts/sync-claude-skills.mjs');
        process.exit(1);
    }
    console.log(`.claude/skills is in sync (${skills.length} skills)`);
} else {
    console.log(`${skills.length} skills mirrored, ${written} file(s) updated`);
}
